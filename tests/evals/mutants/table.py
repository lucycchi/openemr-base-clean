#!/usr/bin/env python3
"""Writes the kill-matrix table into EVAL_GATE.md from tests/evals/mutants/results.json.

The table sits between the markers
    <!-- mutants:start -->  and  <!-- mutants:end -->
and is replaced wholesale on every run (it is generated; do not edit it by hand).

It shows the latest run beside the first one, so a mutant that survived at
first and was killed only by a case written afterwards stays visible. Kills by
the prompt lock are counted apart from kills by the evals: a lock fails on any
edit, so it proves nothing about eval quality (eng review D10).

Usage: table.py <results.json> <EVAL_GATE.md>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

START = "<!-- mutants:start -->"
END = "<!-- mutants:end -->"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def render(runs: list[dict]) -> str:
    first, latest = runs[0], runs[-1]
    first_by_id = {m["id"]: m for m in first["mutants"]}
    mutants = latest["mutants"]
    killed = [m for m in mutants if m["verdict"] == "KILLED"]
    pin = [m for m in killed if m["stage"] == "prompt lock"]
    first_killed = sum(1 for m in first["mutants"] if m["verdict"] == "KILLED")
    lines = [
        START,
        "",
        f"Latest run: {latest['ran_at']} on `{latest['sha'][:10]}`, "
        f"{len(killed)} of {len(mutants)} planted regressions refused by the plain push "
        f"({len(killed) - len(pin)} by the evals and unit tests, {len(pin)} by the prompt lock). "
        f"First run: {first['ran_at']} on `{first['sha'][:10]}`, {first_killed} of {len(first['mutants'])} refused. "
        "Controls passed before and after; canaries C1 (comment only) SURVIVED and C2 (syntax error) was ERROR, as required.",
        "",
        "| Mutant | Layer | Regression planted | Expected killer | First run | Latest | Caught by | Detail |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for m in mutants:
        first_verdict = first_by_id.get(m["id"], {}).get("verdict", "not in first run")
        lines.append(
            "| {id} | {layer} | {mutation} | {expected} | {first} | **{verdict}** | {stage} | {detail} |".format(
                id=cell(m["id"]), layer=cell(m["layer"]), mutation=cell(m["mutation"]), expected=cell(m["expected"]),
                first=cell(first_verdict), verdict=cell(m["verdict"]), stage=cell(m["stage"]), detail=cell(m["detail"]),
            )
        )
    lines += ["", "Generated by `tests/evals/mutants/table.py` from `tests/evals/mutants/results.json`; do not edit by hand.", "", END]
    return "\n".join(lines)


def main() -> None:
    results, doc = Path(sys.argv[1]), Path(sys.argv[2])
    runs = json.loads(results.read_text())
    if not runs:
        return
    text = doc.read_text()
    block = render(runs)
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        text = head + block + tail
    else:
        text = text.rstrip("\n") + "\n\n## Kill matrix\n\n" + block + "\n"
    doc.write_text(text)


if __name__ == "__main__":
    main()
