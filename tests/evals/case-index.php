<?php

/**
 * Regenerates the case index in tests/evals/README.md from the case files, so
 * the documented failure mode of every eval case cannot drift from the case
 * itself. Run after adding or editing a case:
 *
 *   php tests/evals/case-index.php          # rewrite the table in README.md
 *   php tests/evals/case-index.php --check  # fail if the table is stale (used by the gate)
 *
 * Every case must declare `guards` (exactly one of invariant, boundary,
 * regression; access-control cases are invariants with `theme: authorization`)
 * and a `failure_mode` in plain English of at least 40 characters: the suite
 * is designed around boundaries, invariants and known regressions, not happy
 * paths. Why: clinical_copilot_week2/ENGINEERING_REQUIREMENTS.md section 1.
 *
 * @package   OpenEMR
 * @link      https://www.open-emr.org
 * @author    Lucy Chi <lucychi@berkeley.edu>
 * @copyright Copyright (c) 2026 Lucy Chi
 * @license   https://github.com/openemr/openemr/blob/master/LICENSE GNU General Public License 3
 */

declare(strict_types=1);

namespace OpenEMR\Tests\Evals;

use Symfony\Component\Console\Input\ArgvInput;

require_once dirname(__DIR__, 2) . '/vendor/autoload.php';
require_once __DIR__ . '/lib.php';

// The two HTML comments that bracket the generated table in README.md; only
// the text between them is rewritten, so the rest of the README is untouched.
const START = '<!-- CASES:BEGIN (generated by tests/evals/case-index.php; do not edit by hand) -->';
const END = '<!-- CASES:END -->';
const GUARDS = ['invariant', 'boundary', 'regression'];

// Pass 1: read every case, validate its guards and failure_mode, and build one table row.
// Problems are collected rather than thrown so one run reports them all.
$rows = [];
$counts = array_fill_keys(GUARDS, 0);
$problems = [];
foreach (glob(__DIR__ . '/cases/*.json') ?: [] as $path) {
    $case = json_decode((string) file_get_contents($path), true, 32, JSON_THROW_ON_ERROR);
    if (!is_array($case)) {
        $problems[] = basename($path) . ': not an object';
        continue;
    }
    $id = str($case, 'id', basename($path, '.json'));
    $guards = str($case, 'guards');
    $failure = trim(str($case, 'failure_mode'));
    if (!in_array($guards, GUARDS, true)) {
        $problems[] = "$id: guards must be one of " . implode(', ', GUARDS) . ", got " . json_encode($case['guards'] ?? null);
    } else {
        $counts[$guards]++;
    }
    if (mb_strlen($failure) < 40) {
        $problems[] = "$id: failure_mode is missing or too short to be useful";
    }
    $kind = ($case['live'] ?? false) === true ? 'live' : (($case['pending'] ?? false) === true ? 'pending' : 'recorded');
    $theme = is_string($case['theme'] ?? null) ? ' (' . $case['theme'] . ')' : '';
    $rows[] = sprintf('| %s | %s%s | %s | %s | %s |', $id, $guards, $theme, str($case, 'mode', 'briefing'), $kind, str_replace('|', '\\|', $failure));
}

$table = implode("\n", [
    sprintf('%d cases: %s.', count($rows), implode(', ', array_map(fn(string $g): string => "{$counts[$g]} $g", GUARDS))),
    '',
    '| Case | Guards | Mode | Kind | Failure mode it guards against |',
    '|---|---|---|---|---|',
    ...$rows,
]);

// Pass 2: splice the table between the markers. --check compares instead of writing, so the
// gate can refuse a push whose README table no longer matches the case files.
$readme = __DIR__ . '/README.md';
$text = (string) file_get_contents($readme);
$start = strpos($text, START);
$end = strpos($text, END);
if ($start === false || $end === false) {
    fwrite(STDERR, "README.md has no CASES markers\n");
    exit(2);
}
$updated = substr($text, 0, $start) . START . "\n\n" . $table . "\n\n" . substr($text, $end);

if ((new ArgvInput())->hasParameterOption('--check', true)) {
    foreach ($problems as $p) {
        fwrite(STDERR, "case index: $p\n");
    }
    if ($updated !== $text) {
        fwrite(STDERR, "case index: tests/evals/README.md is stale; run php tests/evals/case-index.php\n");
    }
    exit($problems === [] && $updated === $text ? 0 : 1);
}
file_put_contents($readme, $updated);
printf("%d cases indexed (%s)%s\n", count($rows), implode(', ', array_map(fn(string $g): string => "{$counts[$g]} $g", GUARDS)), $problems === [] ? '' : "\n" . implode("\n", $problems));
exit($problems === [] ? 0 : 1);
